import { describe, expect, it } from "vitest"
import { type EmittedIcon } from "./emit"
import { docLines, iosEmitter, swiftCase } from "./emit-ios"

const stroke = (d: string) => ({ d, filled: false, evenOdd: false, unstroked: false, attrs: { d } })

const FIXTURE: EmittedIcon[] = [
  { name: "home", base: "home", variant: null, meaning: "Home: a roof over a door.", paths: [stroke("M3.6 20 L12.1 4.9"), stroke("M2.4 20.2 L21.6 20")] },
  {
    name: "home.active",
    base: "home",
    variant: "active",
    meaning: "Home: a roof over a door.",
    paths: [
      stroke("M3.6 20 L12.1 4.9"),
      { d: "M9 20 L12 14 L15 20 Z M11 18 L13 18 Z", filled: true, evenOdd: true, unstroked: true, attrs: {} },
    ],
  },
  { name: "trash", base: "trash", variant: null, meaning: "Delete: a bin.", paths: [stroke("M4 6 L20 6")] },
]

const CATALOG = "apps/ios/Pebbles/Resources/Icons.xcassets"
const SWIFT = "apps/ios/Pebbles/Theme/PbblsIcon.swift"

const HOME_CONTENTS = `{
  "images" : [
    {
      "filename" : "pbbls-home.svg",
      "idiom" : "universal"
    }
  ],
  "info" : {
    "author" : "xcode",
    "version" : 1
  },
  "properties" : {
    "preserves-vector-representation" : true,
    "template-rendering-intent" : "template"
  }
}
`

const HOME_SVG = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="#000000" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">
  <path d="M3.6 20 L12.1 4.9"/>
  <path d="M2.4 20.2 L21.6 20"/>
</svg>
`

const SWIFT_FILE = `// Generated by packages/icons — do not edit. Run npm run generate --workspace=@pbbls/icons.
// swiftlint:disable file_length
import SwiftUI

/// The hand-drawn Pebbles icon set (\`packages/icons\`): one case per emitted
/// icon and twin, the raw value being the manifest name. Each case is a
/// template image in \`Icons.xcassets\`; draw it with \`PbblsIconImage\`.
enum PbblsIcon: String, CaseIterable, Sendable {
    /// Home: a roof over a door.
    case home = "home"
    /// Home: a roof over a door. (the \`active\` twin)
    case homeActive = "home.active"
    /// Delete: a bin.
    case trash = "trash"

    /// The image's name in \`Icons.xcassets\`: \`pbbls-<name>-<variant>\`.
    var assetName: String {
        "pbbls-" + rawValue.split(whereSeparator: { $0 == "." || $0 == "-" }).joined(separator: "-")
    }

    /// The manifest row this case belongs to: its own name, or its base's for a twin.
    var base: String {
        String(rawValue.prefix { $0 != "." })
    }

    /// The row's \`active\` twin (the lit seal), or nil when it has none.
    var activeTwin: PbblsIcon? {
        PbblsIcon(rawValue: "\\(base).active")
    }

    /// The row's \`lit-n\` twin (n stones lit, 1...3), or nil when it has none.
    func lit(_ n: Int) -> PbblsIcon? {
        PbblsIcon(rawValue: "\\(base).lit-\\(n)")
    }
}

/// A \`PbblsIcon\` drawn as a template image on a square side that follows
/// Dynamic Type through \`@ScaledMetric\` (24pt at the default size, relative to
/// \`.body\` unless told otherwise). It takes the ambient foreground style unless
/// \`style\` is given, and is hidden from accessibility unless \`label\` is.
struct PbblsIconImage: View {
    private let icon: PbblsIcon
    private let style: AnyShapeStyle?
    private let label: LocalizedStringResource?
    @ScaledMetric private var side: CGFloat

    init(_ icon: PbblsIcon, size: CGFloat = 24, relativeTo textStyle: Font.TextStyle = .body,
         style: AnyShapeStyle? = nil, label: LocalizedStringResource? = nil) {
        self.icon = icon
        self.style = style
        self.label = label
        _side = ScaledMetric(wrappedValue: size, relativeTo: textStyle)
    }

    var body: some View {
        let image = Image(icon.assetName)
            .renderingMode(.template)
            .resizable()
            .scaledToFit()
            .frame(width: side, height: side)
        labelled(styled(image))
    }

    @ViewBuilder
    private func styled<Content: View>(_ content: Content) -> some View {
        if let style {
            content.foregroundStyle(style)
        } else {
            content
        }
    }

    @ViewBuilder
    private func labelled<Content: View>(_ content: Content) -> some View {
        if let label {
            content.accessibilityLabel(Text(label))
        } else {
            content.accessibilityHidden(true)
        }
    }
}
`

describe("iosEmitter", () => {
  const files = iosEmitter.emit(FIXTURE)

  it("owns the catalog and the Swift file", () => {
    expect(iosEmitter.owned).toEqual({ dirs: [CATALOG], files: [SWIFT], patterns: [] })
  })

  it("writes the catalog root, one imageset per icon and the Swift file", () => {
    expect([...files.keys()]).toEqual([
      `${CATALOG}/Contents.json`,
      `${CATALOG}/pbbls-home.imageset/Contents.json`,
      `${CATALOG}/pbbls-home.imageset/pbbls-home.svg`,
      `${CATALOG}/pbbls-home-active.imageset/Contents.json`,
      `${CATALOG}/pbbls-home-active.imageset/pbbls-home-active.svg`,
      `${CATALOG}/pbbls-trash.imageset/Contents.json`,
      `${CATALOG}/pbbls-trash.imageset/pbbls-trash.svg`,
      SWIFT,
    ])
  })

  it("writes Contents.json in Xcode's own style", () => {
    expect(files.get(`${CATALOG}/Contents.json`)).toBe(`{
  "info" : {
    "author" : "xcode",
    "version" : 1
  }
}
`)
    expect(files.get(`${CATALOG}/pbbls-home.imageset/Contents.json`)).toBe(HOME_CONTENTS)
    expect(files.get(`${CATALOG}/pbbls-trash.imageset/Contents.json`)).toBe(HOME_CONTENTS.replace("pbbls-home.svg", "pbbls-trash.svg"))
  })

  it("sizes the svg and replaces currentColor with black", () => {
    expect(files.get(`${CATALOG}/pbbls-home.imageset/pbbls-home.svg`)).toBe(HOME_SVG)
    for (const [path, contents] of files) if (path.endsWith(".svg")) expect(contents).not.toContain("currentColor")
  })

  it("passes a lit, carved, unstroked shape through", () => {
    const active = files.get(`${CATALOG}/pbbls-home-active.imageset/pbbls-home-active.svg`) ?? ""
    expect(active).toContain('<path d="M9 20 L12 14 L15 20 Z M11 18 L13 18 Z" fill="#000000" fill-rule="evenodd" stroke="none"/>')
  })

  it("emits the Swift file verbatim", () => {
    expect(files.get(SWIFT)).toBe(SWIFT_FILE)
  })

  it("wraps a long meaning under SwiftLint's line width", () => {
    const long = Array.from({ length: 40 }, (_, i) => `word${i}`).join(" ")
    const lines = docLines(long)
    expect(lines.length).toBeGreaterThan(1)
    for (const line of lines) {
      expect(line.length).toBeLessThanOrEqual(120)
      expect(line.startsWith("    /// ")).toBe(true)
    }
    expect(lines.map((l) => l.slice(8)).join(" ")).toBe(long)
    expect(docLines("short")).toEqual(["    /// short"])
  })

  it("backticks a case that is a Swift keyword", () => {
    expect(swiftCase("check-circle")).toBe("checkCircle")
    expect(swiftCase("case")).toBe("`case`")
    expect(swiftCase("case.lit-1")).toBe("caseLit1")
    const keyword: EmittedIcon = { name: "case", base: "case", variant: null, meaning: "A bound set.", paths: [stroke("M4 6 L20 6")] }
    expect(iosEmitter.emit([keyword]).get(SWIFT)).toContain('    case `case` = "case"')
  })

  it("is deterministic", () => {
    expect(iosEmitter.emit(FIXTURE)).toEqual(files)
  })
})
