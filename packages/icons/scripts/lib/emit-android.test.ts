import { describe, expect, it } from "vitest"
import { type EmittedIcon } from "./emit"
import { androidEmitter, kdocLines, xmlComment } from "./emit-android"

const stroke = (d: string) => ({ d, filled: false, evenOdd: false, unstroked: false, attrs: { d } })

const FIXTURE: EmittedIcon[] = [
  { name: "home", base: "home", variant: null, meaning: "Home: a roof over a door.", paths: [stroke("M3.6 20 L12.1 4.9"), stroke("M2.4 20.2 L21.6 20")] },
  {
    name: "home.active",
    base: "home",
    variant: "active",
    meaning: "Home: a roof over a door.",
    paths: [
      stroke("M3.6 20 L12.1 4.9"),
      { d: "M9 20 L12 14 L15 20 Z M11 18 L13 18 Z", filled: true, evenOdd: true, unstroked: true, attrs: {} },
    ],
  },
  { name: "trash", base: "trash", variant: null, meaning: "Delete: a bin.", paths: [stroke("M4 6 L20 6")] },
]

const DRAWABLE = "apps/android/app/src/main/res/drawable"
const KOTLIN = "apps/android/app/src/main/kotlin/app/pbbls/android/core/designsystem/PbblsIcons.kt"

const HOME_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by packages/icons (home): Home: a roof over a door. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path
        android:pathData="M3.6 20 L12.1 4.9"
        android:strokeColor="#FFFFFFFF"
        android:strokeWidth="1.75"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:fillColor="#00000000" />
    <path
        android:pathData="M2.4 20.2 L21.6 20"
        android:strokeColor="#FFFFFFFF"
        android:strokeWidth="1.75"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:fillColor="#00000000" />
</vector>
`

const HOME_ACTIVE_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by packages/icons (home.active): Home: a roof over a door. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path
        android:pathData="M3.6 20 L12.1 4.9"
        android:strokeColor="#FFFFFFFF"
        android:strokeWidth="1.75"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:fillColor="#00000000" />
    <path
        android:pathData="M9 20 L12 14 L15 20 Z M11 18 L13 18 Z"
        android:fillColor="#FFFFFFFF"
        android:fillType="evenOdd"
        tools:ignore="VectorPath" />
</vector>
`

const KOTLIN_FILE = `// Generated by packages/icons — do not edit. Run npm run generate --workspace=@pbbls/icons.
package app.pbbls.android.core.designsystem

import androidx.annotation.DrawableRes
import androidx.compose.foundation.layout.size
import androidx.compose.material3.Icon
import androidx.compose.material3.LocalContentColor
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.res.painterResource
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp
import app.pbbls.android.R

/**
 * The hand-drawn Pebbles icon set (\`packages/icons\`): one entry per emitted
 * icon and twin, [manifestName] being the manifest name. Each entry is a
 * \`VectorDrawable\` under \`res/drawable/ic_pbbls_*\`; draw it with [PbblsIconImage].
 */
enum class PbblsIcon(
    val manifestName: String,
    @DrawableRes val drawableRes: Int,
) {
    /** Home: a roof over a door. */
    HOME("home", R.drawable.ic_pbbls_home),

    /** Home: a roof over a door. (the \`active\` twin) */
    HOME_ACTIVE("home.active", R.drawable.ic_pbbls_home_active),

    /** Delete: a bin. */
    TRASH("trash", R.drawable.ic_pbbls_trash),
    ;

    /** The manifest row this entry belongs to: its own name, or its base's for a twin. */
    val base: String
        get() = manifestName.substringBefore('.')

    /** The row's \`active\` twin (the lit seal), or null when it has none. */
    val activeTwin: PbblsIcon?
        get() = fromManifestName("$base.active")

    /** The row's \`lit-n\` twin (n stones lit, 1..3), or null when it has none. */
    fun lit(n: Int): PbblsIcon? = fromManifestName("$base.lit-$n")

    companion object {
        private val byManifestName = entries.associateBy { it.manifestName }

        /** The entry whose [manifestName] is [name], or null. */
        fun fromManifestName(name: String): PbblsIcon? = byManifestName[name]
    }
}

/**
 * A [PbblsIcon] drawn through [Icon] on a square [size] side (24dp by default:
 * icons keep dp and do not follow the font scale, the Material convention). It
 * takes [LocalContentColor] unless [tint] is given, and is hidden from
 * accessibility unless [contentDescription] is.
 */
@Composable
fun PbblsIconImage(
    icon: PbblsIcon,
    contentDescription: String?,
    modifier: Modifier = Modifier,
    size: Dp = 24.dp,
    tint: Color = LocalContentColor.current,
) {
    Icon(
        painter = painterResource(icon.drawableRes),
        contentDescription = contentDescription,
        tint = tint,
        modifier = modifier.size(size),
    )
}
`

describe("androidEmitter", () => {
  const files = androidEmitter.emit(FIXTURE)

  it("owns the ic_pbbls_ drawables and the Kotlin file, nothing else in res/drawable", () => {
    expect(androidEmitter.owned).toEqual({
      dirs: [],
      files: [KOTLIN],
      patterns: [{ dir: DRAWABLE, prefix: "ic_pbbls_", suffix: ".xml" }],
    })
  })

  it("writes one drawable per icon and the Kotlin file", () => {
    expect([...files.keys()]).toEqual([
      `${DRAWABLE}/ic_pbbls_home.xml`,
      `${DRAWABLE}/ic_pbbls_home_active.xml`,
      `${DRAWABLE}/ic_pbbls_trash.xml`,
      KOTLIN,
    ])
  })

  it("emits a stroked drawable with the path data verbatim", () => {
    expect(files.get(`${DRAWABLE}/ic_pbbls_home.xml`)).toBe(HOME_XML)
  })

  it("emits a lit, carved, unstroked shape as an even-odd fill with no stroke, ignoring VectorPath", () => {
    expect(files.get(`${DRAWABLE}/ic_pbbls_home_active.xml`)).toBe(HOME_ACTIVE_XML)
  })

  it("declares the tools namespace only on a carved drawable", () => {
    expect(files.get(`${DRAWABLE}/ic_pbbls_home.xml`)).not.toContain("xmlns:tools")
    expect(files.get(`${DRAWABLE}/ic_pbbls_trash.xml`)).not.toContain("tools:")
  })

  it("keeps the stroke on a lit shape that still has one", () => {
    const lit: EmittedIcon = {
      name: "stone.lit-1",
      base: "stone",
      variant: "lit-1",
      meaning: "A stone.",
      paths: [{ d: "M4 4 L20 20", filled: true, evenOdd: false, unstroked: false, attrs: {} }],
    }
    expect(androidEmitter.emit([lit]).get(`${DRAWABLE}/ic_pbbls_stone_lit_1.xml`)).toContain(`    <path
        android:pathData="M4 4 L20 20"
        android:strokeColor="#FFFFFFFF"
        android:strokeWidth="1.75"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:fillColor="#FFFFFFFF" />`)
  })

  it("emits the Kotlin file verbatim", () => {
    expect(files.get(KOTLIN)).toBe(KOTLIN_FILE)
  })

  it("never closes the XML comment early", () => {
    expect(xmlComment("home", "A two-dash -- meaning --> gone")).toBe(
      "<!-- Generated by packages/icons (home): A two-dash - - meaning - -> gone Do not edit. -->",
    )
    expect(xmlComment("home", "Plain.")).not.toContain("- -")
  })

  it("wraps a long KDoc under 140 columns", () => {
    const long = Array.from({ length: 40 }, (_, i) => `word${i}`).join(" ")
    const lines = kdocLines(long)
    expect(lines.length).toBeGreaterThan(3)
    expect(lines[0]).toBe("    /**")
    expect(lines[lines.length - 1]).toBe("     */")
    for (const line of lines) expect(line.length).toBeLessThanOrEqual(140)
    expect(lines.slice(1, -1).map((l) => l.slice(7)).join(" ")).toBe(long)
    expect(kdocLines("short")).toEqual(["    /** short */"])
  })

  it("is deterministic", () => {
    expect(androidEmitter.emit(FIXTURE)).toEqual(files)
  })
})
