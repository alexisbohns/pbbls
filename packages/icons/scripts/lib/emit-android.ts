/**
 * The Android emitter (spec §5, D9): one `VectorDrawable` per icon under
 * `apps/android/app/src/main/res/drawable/ic_pbbls_<snake>.xml` (the generator
 * owns the `ic_pbbls_*` drawables only; the hand-traced `ic_*` around them
 * are untouched) and `core/designsystem/PbblsIcons.kt`, the enum that mirrors
 * iOS `PbblsIcon` (`base`, `activeTwin`, `lit(n)`) and `PbblsIconImage` over
 * `Icon`. Every path is white and tinted at the call site by `LocalContentColor`.
 */
import { GENERATED_NOTICE, type EmittedIcon, type Emitter } from "./emit"
import { constantName, drawableName } from "./names"
import { type ParsedPath } from "./parse"

export const DRAWABLE_DIR = "apps/android/app/src/main/res/drawable"
export const KOTLIN_FILE = "apps/android/app/src/main/kotlin/app/pbbls/android/core/designsystem/PbblsIcons.kt"

/** An XML comment may not hold `--`, so a meaning's double dash is split. */
export function xmlComment(name: string, meaning: string): string {
  return `<!-- Generated by packages/icons (${name}): ${meaning.replaceAll("--", "- -")} Do not edit. -->`
}

function pathElement(path: ParsedPath): string {
  const attrs = [`android:pathData="${path.d}"`]
  if (!path.unstroked) {
    attrs.push(
      'android:strokeColor="#FFFFFFFF"',
      'android:strokeWidth="1.75"',
      'android:strokeLineCap="round"',
      'android:strokeLineJoin="round"',
    )
  }
  attrs.push(path.filled ? 'android:fillColor="#FFFFFFFF"' : 'android:fillColor="#00000000"')
  // A carved stone (D11) is one compound path, long by construction: the
  // mark's stroke outlined around the stone. Lint's `VectorPath` is fatal
  // under `warningsAsErrors`, so the carve carries its own suppression.
  if (path.evenOdd) attrs.push('android:fillType="evenOdd"', 'tools:ignore="VectorPath"')
  return `    <path\n${attrs.map((a) => `        ${a}`).join("\n")} />`
}

export function drawableXml(icon: EmittedIcon): string {
  const tools = icon.paths.some((p) => p.evenOdd) ? '\n    xmlns:tools="http://schemas.android.com/tools"' : ""
  return `<?xml version="1.0" encoding="utf-8"?>
${xmlComment(icon.name, icon.meaning)}
<vector xmlns:android="http://schemas.android.com/apk/res/android"${tools}
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
${icon.paths.map(pathElement).join("\n")}
</vector>
`
}

/** ktlint's stock `max-line-length` for a generated KDoc or entry line. */
const LINE_WIDTH = 140
const INDENT = "    "
const BODY_PREFIX = `${INDENT} * `

/** A KDoc on one line when it fits, else word-wrapped under `LINE_WIDTH`. */
export function kdocLines(text: string): string[] {
  const words = text.split(/\s+/).filter((w) => w.length > 0)
  const single = `${INDENT}/** ${words.join(" ")} */`
  if (single.length <= LINE_WIDTH) return [single]
  const lines: string[] = []
  let line = ""
  for (const word of words) {
    if (line.length > 0 && BODY_PREFIX.length + line.length + 1 + word.length > LINE_WIDTH) {
      lines.push(line)
      line = word
    } else {
      line = line.length === 0 ? word : `${line} ${word}`
    }
  }
  if (line.length > 0) lines.push(line)
  return [`${INDENT}/**`, ...lines.map((l) => BODY_PREFIX + l), `${INDENT} */`]
}

function entryLines(icon: EmittedIcon): string {
  const twin = icon.variant === null ? "" : ` (the \`${icon.variant}\` twin)`
  return [...kdocLines(icon.meaning + twin), ...callLines(INDENT, constantName(icon.name), [`"${icon.name}"`], ",")].join("\n")
}

/** `name(a, b)` on one line when it fits ktlint's max-line-length, else one argument per line with a trailing comma. */
function callLines(indent: string, name: string, args: string[], end: string): string[] {
  const single = `${indent}${name}(${args.join(", ")})${end}`
  if (single.length <= LINE_WIDTH) return [single]
  return [`${indent}${name}(`, ...args.map((a) => `${indent}${INDENT}${a},`), `${indent})${end}`]
}

/**
 * Drawable ids per function. The ids are read in these small functions, never
 * in the enum's initializer: with 1,878 entries each reading \`R.drawable\`
 * there, the initializer passed the JVM's 64 KB method limit once layoutlib
 * (the screenshot previews) rewrote its bytecode, and every preview drawing an
 * icon failed to render. A chunk of 500 compiles to about 4 KB.
 */
const DRAWABLE_CHUNK = 500

function drawableLines(icons: EmittedIcon[]): string {
  const chunks: EmittedIcon[][] = []
  for (let i = 0; i < icons.length; i += DRAWABLE_CHUNK) chunks.push(icons.slice(i, i + DRAWABLE_CHUNK))
  const spread = chunks.map((_, i) => `*drawableIds${i}()`)
  return [
    "/** Each entry's drawable, in entry order: read through [PbblsIcon.drawableRes]. */",
    ...callLines("", "private val drawableIds: IntArray = intArrayOf", spread, ""),
    ...chunks.flatMap((chunk, i) => [
      "",
      `private fun drawableIds${i}(): IntArray =`,
      `${INDENT}intArrayOf(`,
      ...chunk.map((icon) => `${INDENT}${INDENT}R.drawable.${drawableName(icon.name)},`),
      `${INDENT})`,
    ]),
  ].join("\n")
}

export function kotlinFile(icons: EmittedIcon[]): string {
  return `// ${GENERATED_NOTICE}
package app.pbbls.android.core.designsystem

import androidx.annotation.DrawableRes
import androidx.compose.foundation.layout.size
import androidx.compose.material3.Icon
import androidx.compose.material3.LocalContentColor
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.res.painterResource
import androidx.compose.ui.unit.Dp
import androidx.compose.ui.unit.dp
import app.pbbls.android.R

/**
 * The hand-drawn Pebbles icon set (\`packages/icons\`): one entry per emitted
 * icon and twin, [manifestName] being the manifest name. Each entry is a
 * \`VectorDrawable\` under \`res/drawable/ic_pbbls_*\`; draw it with [PbblsIconImage].
 */
enum class PbblsIcon(
    val manifestName: String,
) {
${icons.map(entryLines).join("\n\n")}
    ;

    /** The entry's \`VectorDrawable\`, \`R.drawable.ic_pbbls_*\`. */
    @get:DrawableRes
    val drawableRes: Int
        get() = drawableIds[ordinal]

    /** The manifest row this entry belongs to: its own name, or its base's for a twin. */
    val base: String
        get() = manifestName.substringBefore('.')

    /** The row's \`active\` twin (the lit seal), or null when it has none. */
    val activeTwin: PbblsIcon?
        get() = fromManifestName("$base.active")

    /** The row's \`lit-n\` twin (n stones lit, 1..3), or null when it has none. */
    fun lit(n: Int): PbblsIcon? = fromManifestName("$base.lit-$n")

    companion object {
        private val byManifestName = entries.associateBy { it.manifestName }

        /** The entry whose [manifestName] is [name], or null. */
        fun fromManifestName(name: String): PbblsIcon? = byManifestName[name]
    }
}

/**
 * A [PbblsIcon] drawn through [Icon] on a square [size] side (24dp by default:
 * icons keep dp and do not follow the font scale, the Material convention). It
 * takes [LocalContentColor] unless [tint] is given, and is hidden from
 * accessibility unless [contentDescription] is.
 */
@Composable
fun PbblsIconImage(
    icon: PbblsIcon,
    contentDescription: String?,
    modifier: Modifier = Modifier,
    size: Dp = 24.dp,
    tint: Color = LocalContentColor.current,
) {
    Icon(
        painter = painterResource(icon.drawableRes),
        contentDescription = contentDescription,
        tint = tint,
        modifier = modifier.size(size),
    )
}

${drawableLines(icons)}
`
}

export const androidEmitter: Emitter = {
  name: "android",
  owned: { dirs: [], files: [KOTLIN_FILE], patterns: [{ dir: DRAWABLE_DIR, prefix: "ic_pbbls_", suffix: ".xml" }] },
  emit(icons) {
    const out = new Map<string, string>()
    for (const icon of icons) out.set(`${DRAWABLE_DIR}/${drawableName(icon.name)}.xml`, drawableXml(icon))
    out.set(KOTLIN_FILE, kotlinFile(icons))
    return out
  },
}
