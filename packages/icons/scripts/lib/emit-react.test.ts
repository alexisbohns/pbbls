import { mkdirSync, mkdtempSync, symlinkSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { dirname, join } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"
import { createElement, type FunctionComponent } from "react"
import { renderToStaticMarkup } from "react-dom/server"
import { describe, expect, it } from "vitest"
import { SOLID } from "../../runtime/forms"
import { type EmittedIcon } from "./emit"
import { buildGlyph } from "./emit-glyphs"
import { glyphComponentFile, reactFiles } from "./emit-react"
import { formsOf } from "./forms"
import type { IconRow } from "./manifest"

const RUNTIME_DIR = fileURLToPath(new URL("../../runtime", import.meta.url))

const FIXTURE: EmittedIcon[] = [
  { name: "home", meaning: "Home: a roof over a door." },
  { name: "trash", meaning: "Delete: a bin." },
]

const row = (name: string, meaning: string): IconRow => ({ name, meaning, family: null, tags: { category: ["stones"] }, wave: "w", status: "candidate", migrated: [], replaces: { ios: [], android: [], web: [] } })
const SVG = (inner: string) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${inner}</svg>`
const HOME_GLYPH = buildGlyph(row("home", "Home: a roof over a door."), SVG('<path d="M3.6 20 L12.1 4.9" data-role="body"/><path d="M2.4 20.2 L21.6 20"/><path d="M9 20 L12 14 L15 20" data-role="mark"/>'), {})
const TRASH_GLYPH = buildGlyph(row("trash", "Delete: a bin."), SVG('<path d="M4 6 L20 6"/>'), {})
const GLYPHS = [HOME_GLYPH, TRASH_GLYPH]
const STATES = { rest: ["regular"], selected: ["solid", "regular"] }

const isComponent = (v: unknown): v is FunctionComponent<Record<string, unknown>> => typeof v === "function"

async function importComponent(dir: string, file: string, name: string): Promise<FunctionComponent<Record<string, unknown>>> {
  const mod: unknown = await import(pathToFileURL(join(dir, file)).href)
  if (typeof mod !== "object" || mod === null || !(name in mod)) throw new Error(`${file} does not export ${name}`)
  const value: unknown = Reflect.get(mod, name)
  if (!isComponent(value)) throw new Error(`${file}: ${name} is not a component`)
  return value
}

describe("reactFiles", () => {
  const files = reactFiles(FIXTURE, GLYPHS, STATES)

  it("writes one file per icon plus types, states and index", () => {
    expect([...files.keys()]).toEqual([
      "packages/icons/react/Home.tsx",
      "packages/icons/react/Trash.tsx",
      "packages/icons/react/types.ts",
      "packages/icons/react/states.ts",
      "packages/icons/react/index.ts",
    ])
  })

  it("writes a base component from its glyph: data inlined, forms attached, drawn by GlyphSvg", () => {
    const home = files.get("packages/icons/react/Home.tsx") ?? ""
    expect(home).toBe(glyphComponentFile(HOME_GLYPH))
    expect(home).toContain('import { GlyphSvg } from "../runtime/GlyphSvg"')
    expect(home).toContain("export function Home(props: PbblsGlyphProps) {")
    expect(home).toContain("return <GlyphSvg glyph={GLYPH} {...props} />")
    expect(home).toContain(`Home.forms = ${JSON.stringify(formsOf(HOME_GLYPH))} as const`)
    expect(home).toContain("/** `home` — Home: a roof over a door. */")
    expect(home).not.toMatch(/"meaning"|"tags"|"family"/)
  })

  it("writes the state table and its type", () => {
    const states = files.get("packages/icons/react/states.ts") ?? ""
    expect(states).toContain('export const STATES = {"rest":["regular"],"selected":["solid","regular"]} as const')
    expect(states).toContain("export type PbblsGlyphState = keyof typeof STATES")
  })

  it("re-exports in manifest order, with the types, the states and the runtime", () => {
    expect(files.get("packages/icons/react/index.ts")).toBe(
      `// Generated by packages/icons — do not edit. Run npm run generate --workspace=@pbbls/icons.
export type { PbblsGlyphProps, PbblsGlyphComponent } from "./types"
export { STATES, type PbblsGlyphState } from "./states"
export { glyphForm, REGULAR, MARKED, SOLID, DOTTED, progress, type Form } from "../runtime/public"
export { Home } from "./Home"
export { Trash } from "./Trash"
`,
    )
    const types = files.get("packages/icons/react/types.ts") ?? ""
    expect(types).not.toContain("PbblsIconProps")
    expect(types).toContain("export type PbblsGlyphProps = GlyphSvgProps")
    expect(types).toContain("export type PbblsGlyphComponent")
  })

  it("is deterministic", () => {
    expect(reactFiles(FIXTURE, GLYPHS, STATES)).toEqual(files)
  })

  it("refuses an icon with no glyph", () => {
    expect(() => reactFiles(FIXTURE, [HOME_GLYPH], STATES)).toThrow("trash: no glyph")
  })

  it("renders a glyph hidden by default and as an image when labelled, and in a form", async () => {
    const root = mkdtempSync(join(tmpdir(), "icons-react-"))
    for (const [path, contents] of files) {
      const target = join(root, path)
      mkdirSync(dirname(target), { recursive: true })
      writeFileSync(target, contents)
    }
    // The components import `../runtime/...`: link the real runtime beside the written `react/`.
    // Node resolves a symlink to its real path, so the runtime's own `../scripts/lib` imports
    // and its `react` resolve from the package, with nothing copied that could go stale.
    symlinkSync(RUNTIME_DIR, join(root, "packages/icons/runtime"))
    const dir = join(root, "packages/icons/react")

    const Home = await importComponent(dir, "Home.tsx", "Home")
    const hidden = renderToStaticMarkup(createElement(Home, {}))
    expect(hidden).toContain('aria-hidden="true"')
    expect(hidden).toContain('width="24"')
    expect(hidden).not.toContain("role=")
    const labelled = renderToStaticMarkup(createElement(Home, { "aria-label": "Home", size: 20 }))
    expect(labelled).toContain('role="img"')
    expect(labelled).toContain('width="20"')
    expect(labelled).not.toContain("aria-hidden")
    const solid = renderToStaticMarkup(createElement(Home, { form: SOLID, "aria-label": "Home" }))
    expect(solid).toContain('role="img"')
    expect(solid).toContain('data-form="solid"')
    expect(solid).toContain('fill="currentColor"')
    expect(renderToStaticMarkup(createElement(Home, {}))).toContain('data-form="regular"')
  })
})
