import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { dirname, join } from "node:path"
import { pathToFileURL } from "node:url"
import { createElement, type FunctionComponent } from "react"
import { renderToStaticMarkup } from "react-dom/server"
import { describe, expect, it } from "vitest"
import { type EmittedIcon } from "./emit"
import { reactEmitter } from "./emit-react"

const stroke = (d: string) => ({ d, filled: false, evenOdd: false, unstroked: false, attrs: { d } })

const FIXTURE: EmittedIcon[] = [
  { name: "home", base: "home", variant: null, meaning: "Home: a roof over a door.", paths: [stroke("M3.6 20 L12.1 4.9"), stroke("M2.4 20.2 L21.6 20")] },
  {
    name: "home.active",
    base: "home",
    variant: "active",
    meaning: "Home: a roof over a door.",
    paths: [
      stroke("M3.6 20 L12.1 4.9"),
      { d: "M9 20 L12 14 L15 20 Z M11 18 L13 18 Z", filled: true, evenOdd: true, unstroked: true, attrs: {} },
    ],
  },
  { name: "trash", base: "trash", variant: null, meaning: "Delete: a bin.", paths: [stroke("M4 6 L20 6")] },
]

const HOME = `// Generated by packages/icons — do not edit. Run npm run generate --workspace=@pbbls/icons.
import type { PbblsIconProps } from "./types"

/** \`home\` — Home: a roof over a door. */
export function Home({ size = 24, ...props }: PbblsIconProps) {
  const labelled = props["aria-label"] !== undefined || props["aria-labelledby"] !== undefined
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden={labelled ? undefined : true}
      role={labelled ? "img" : undefined}
      focusable="false"
      {...props}
    >
      <path d="M3.6 20 L12.1 4.9" />
      <path d="M2.4 20.2 L21.6 20" />
    </svg>
  )
}
`

const isComponent = (v: unknown): v is FunctionComponent<Record<string, unknown>> => typeof v === "function"

async function importComponent(dir: string, file: string, name: string): Promise<FunctionComponent<Record<string, unknown>>> {
  const mod: unknown = await import(pathToFileURL(join(dir, file)).href)
  if (typeof mod !== "object" || mod === null || !(name in mod)) throw new Error(`${file} does not export ${name}`)
  const value: unknown = Reflect.get(mod, name)
  if (!isComponent(value)) throw new Error(`${file}: ${name} is not a component`)
  return value
}

describe("reactEmitter", () => {
  const files = reactEmitter.emit(FIXTURE)

  it("owns packages/icons/react", () => {
    expect(reactEmitter.owned).toEqual({ dirs: ["packages/icons/react"], files: [], patterns: [] })
  })

  it("writes one file per icon plus types and index", () => {
    expect([...files.keys()]).toEqual([
      "packages/icons/react/Home.tsx",
      "packages/icons/react/HomeActive.tsx",
      "packages/icons/react/Trash.tsx",
      "packages/icons/react/types.ts",
      "packages/icons/react/index.ts",
    ])
  })

  it("emits the component verbatim", () => {
    expect(files.get("packages/icons/react/Home.tsx")).toBe(HOME)
  })

  it("marks a lit, carved, unstroked shape", () => {
    const active = files.get("packages/icons/react/HomeActive.tsx") ?? ""
    expect(active).toContain("/** `home.active` — Home: a roof over a door. (the `active` twin) */")
    expect(active).toContain("export function HomeActive(")
    expect(active).toContain('<path d="M9 20 L12 14 L15 20 Z M11 18 L13 18 Z" fill="currentColor" fillRule="evenodd" stroke="none" />')
  })

  it("re-exports in manifest order", () => {
    expect(files.get("packages/icons/react/index.ts")).toBe(
      `// Generated by packages/icons — do not edit. Run npm run generate --workspace=@pbbls/icons.
export type { PbblsIconProps } from "./types"
export { Home } from "./Home"
export { HomeActive } from "./HomeActive"
export { Trash } from "./Trash"
`,
    )
    expect(files.get("packages/icons/react/types.ts")).toContain('Omit<SVGProps<SVGSVGElement>, "children"> & { size?: number | string }')
  })

  it("is deterministic", () => {
    expect(reactEmitter.emit(FIXTURE)).toEqual(files)
  })

  it("renders hidden by default and as an image when labelled", async () => {
    const root = mkdtempSync(join(tmpdir(), "icons-react-"))
    for (const [path, contents] of files) {
      const target = join(root, path)
      mkdirSync(dirname(target), { recursive: true })
      writeFileSync(target, contents)
    }
    const Home = await importComponent(join(root, "packages/icons/react"), "Home.tsx", "Home")
    const hidden = renderToStaticMarkup(createElement(Home, {}))
    expect(hidden).toContain('aria-hidden="true"')
    expect(hidden).toContain('width="24"')
    expect(hidden).toContain('focusable="false"')
    expect(hidden).not.toContain("role=")
    const labelled = renderToStaticMarkup(createElement(Home, { "aria-label": "Home", size: 20 }))
    expect(labelled).toContain('role="img"')
    expect(labelled).toContain('aria-label="Home"')
    expect(labelled).toContain('width="20"')
    expect(labelled).not.toContain("aria-hidden")
  })
})
