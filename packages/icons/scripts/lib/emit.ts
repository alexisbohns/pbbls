/**
 * What every emitter consumes and what it promises (spec §5): the emitted rows
 * with their parsed sources, and a pure `emit` that returns repo-relative paths
 * to contents, never touching the disk. `write.ts` owns the disk.
 */
import { readFileSync } from "node:fs"
import { join } from "node:path"
import { SRC_DIR } from "./lint"
import { emitted, loadManifest, type Variant } from "./manifest"
import { sourceFile } from "./names"
import { parseSvg, type ParsedPath } from "./parse"

/** One icon to emit: a manifest row or one of its twins, with its parsed source. */
export type EmittedIcon = {
  /** `home` or `home.active`. */
  name: string
  /** The base row's name (`home` for both). */
  base: string
  variant: Variant | null
  meaning: string
  paths: ParsedPath[]
}

/** Direct children of `dir` named `<prefix>…<suffix>` (the Android drawables among the hand-traced ones). */
export type OwnedPattern = { dir: string; prefix: string; suffix: string }

/**
 * The repo-relative paths an emitter owns outright: whole directories, exact
 * files and patterns. `write` clears them before writing, `check` reports what
 * lies there and was not emitted.
 */
export type OwnedPaths = { dirs: string[]; files: string[]; patterns: OwnedPattern[] }

export type Emitter = {
  name: string
  owned: OwnedPaths
  emit(icons: EmittedIcon[]): Map<string, string>
}

/** The first line of every generated file (without the comment syntax). */
export const GENERATED_NOTICE = "Generated by packages/icons — do not edit. Run npm run generate --workspace=@pbbls/icons."

/** Reads `icons.json` and parses the source of every emitted row and twin, in manifest order. */
export function loadIcons(packageRoot: string): EmittedIcon[] {
  return emitted(loadManifest(packageRoot)).map((row) => {
    const file = sourceFile(row.name)
    let text: string
    try {
      text = readFileSync(join(packageRoot, SRC_DIR, file), "utf8")
    } catch {
      throw new Error(`${row.name}: cannot read ${SRC_DIR}/${file}`)
    }
    const { paths } = parseSvg(text, `${SRC_DIR}/${file}`)
    return { name: row.name, base: row.base, variant: row.variant, meaning: row.meaning, paths }
  })
}

/** The union of several emitters' owned paths. */
export function unionOwned(emitters: readonly Emitter[]): OwnedPaths {
  return {
    dirs: emitters.flatMap((e) => e.owned.dirs),
    files: emitters.flatMap((e) => e.owned.files),
    patterns: emitters.flatMap((e) => e.owned.patterns),
  }
}
