// Splits an engine shape seed (`docs/seeds/shape-seeds/*.svg`) into the parts
// the lit stone carves separately. Port of iOS `StoneShapeParser`, so the two
// surfaces read the seeds the same way.
//
// The engine emits no ids. The outline is the stroked `<path>` with the largest
// extent (`large-neutral` lists it third, so document order is not enough),
// every other stroked path is a vein in document order, and the single filled
// path is the fossil.

export type SeedStroke = { d: string; width: number }
export type SeedFill = { d: string; fillRule: "evenodd" | "nonzero" }

export type ShapeSeed = {
  width: number
  height: number
  outline: SeedStroke
  veins: SeedStroke[]
  fossil: SeedFill | null
}

const PATH = /<path\s+([^>]*?)\/?>/g
const ATTRIBUTE = /([\w-]+)="([^"]*)"/g
const VIEW_BOX = /viewBox="([^"]*)"/

export function parseShapeSeed(svg: string): ShapeSeed | null {
  const viewBox = VIEW_BOX.exec(svg)?.[1].split(/[\s,]+/).map(Number)
  if (!viewBox || viewBox.length !== 4 || viewBox.some(Number.isNaN)) return null

  const strokes: SeedStroke[] = []
  let fossil: SeedFill | null = null
  for (const [, body] of svg.matchAll(PATH)) {
    const attributes = new Map([...body.matchAll(ATTRIBUTE)].map(([, key, value]) => [key, value]))
    const d = attributes.get("d")
    if (!d) continue
    const fill = attributes.get("fill")
    if (fill && fill !== "none") {
      // Keep the first filled path only: the engine emits one fossil.
      fossil ??= { d, fillRule: attributes.get("fill-rule") === "evenodd" ? "evenodd" : "nonzero" }
    } else if (attributes.has("stroke")) {
      strokes.push({ d, width: Number(attributes.get("stroke-width") ?? 6) || 6 })
    }
  }
  if (strokes.length === 0) return null

  let outlineIndex = 0
  strokes.forEach((stroke, i) => {
    if (extent(stroke.d) > extent(strokes[outlineIndex].d)) outlineIndex = i
  })
  const veins = strokes.filter((_, i) => i !== outlineIndex)
  return { width: viewBox[2], height: viewBox[3], outline: strokes[outlineIndex], veins, fossil }
}

/**
 * Bounding-box area of a path's raw coordinates: enough to tell the outline
 * (the whole canvas) from a vein (a strip of it) without parsing the path.
 */
function extent(d: string): number {
  const numbers = d.split(/[^0-9.-]+/).filter(Boolean).map(Number).filter((n) => !Number.isNaN(n))
  if (numbers.length < 4) return 0
  const xs = numbers.filter((_, i) => i % 2 === 0)
  const ys = numbers.filter((_, i) => i % 2 === 1)
  return (Math.max(...xs) - Math.min(...xs)) * (Math.max(...ys) - Math.min(...ys))
}

const SIZES = ["small", "medium", "large"] as const
const POLARITIES = ["lowlight", "neutral", "highlight"] as const

/** `docs/seeds/shape-seeds/` relative to apps/web. */
export const SHAPE_SEEDS_FROM_WEB = "../../docs/seeds/shape-seeds"
/** The generated table, relative to apps/web. */
export const STONE_CARVINGS_FROM_WEB = "lib/config/stone-carvings.ts"

export function shapeSeedFile(size: string, polarity: string): string {
  return `${size}-${polarity}.svg`
}

/**
 * Renders `lib/config/stone-carvings.ts` from the nine seed files, keyed
 * `${size}-${polarity}`. The outline is parsed (so it is never mistaken for a
 * vein) but not emitted: the stone's edge is its own silhouette (spec D3).
 */
export function renderStoneCarvings(readSeed: (file: string) => string): string {
  const rows: string[] = []
  for (const size of SIZES) {
    rows.push(`  ${size}: {`)
    for (const polarity of POLARITIES) {
      const file = shapeSeedFile(size, polarity)
      const seed = parseShapeSeed(readSeed(file))
      if (!seed) throw new Error(`[stone-carvings] ${file} did not parse`)
      rows.push(`    ${polarity}: {`)
      rows.push(`      width: ${seed.width},`)
      rows.push(`      height: ${seed.height},`)
      if (seed.veins.length === 0) {
        rows.push(`      veins: [],`)
      } else {
        rows.push(`      veins: [`)
        for (const vein of seed.veins) rows.push(`        { width: ${vein.width}, d: ${JSON.stringify(vein.d)} },`)
        rows.push(`      ],`)
      }
      rows.push(
        seed.fossil
          ? `      fossil: { fillRule: ${JSON.stringify(seed.fossil.fillRule)}, d: ${JSON.stringify(seed.fossil.d)} },`
          : `      fossil: null,`,
      )
      rows.push(`    },`)
    }
    rows.push(`  },`)
  }
  return `// GENERATED by \`npm run generate:stone-carvings --workspace=apps/web\` from
// docs/seeds/shape-seeds/*.svg. Do not edit: change the seeds and re-run.
// \`stone-carvings.test.ts\` fails when this file drifts from them.
//
// Each engine shape seed's veins and fossil, in the seed's own canvas units.
// The seed outline is left out: the lit stone's edge is the wobbled backdrop
// silhouette, and the engine outline is not drawn (spec D3).

import type { Polarity, Size } from "./pebble-geometry"
import type { SeedFill, SeedStroke } from "@/lib/utils/spine/shape-seed"

export type StoneCarving = {
  /** The engine canvas for this size. */
  width: number
  height: number
  veins: SeedStroke[]
  fossil: SeedFill | null
}

export const STONE_CARVINGS: Record<Size, Record<Polarity, StoneCarving>> = {
${rows.join("\n")}
}
`
}
